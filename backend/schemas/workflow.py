"""Workflow and specialized agent input/output schemas."""

from enum import StrEnum
from typing import Any, Literal

from pydantic import BaseModel, Field, model_validator

from backend.schemas.agent import AgentExecutionMetrics
from backend.schemas.task import SubTask


class WorkflowStatus(StrEnum):
    """Lifecycle status of a multi-agent workflow execution."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    PARTIAL = "partial"


class SourceReference(BaseModel):
    """Reference to an external document, URL, or tool output."""

    title: str = Field(..., min_length=1, max_length=512)
    url: str | None = Field(default=None, max_length=1024)
    snippet: str = Field(default="", max_length=4096)
    source_type: str = Field(default="web", max_length=64)


class ExecutionPlan(BaseModel):
    """Validated DAG execution plan generated by the Planner Agent."""

    goal: str = Field(..., min_length=1)
    summary: str = Field(..., min_length=1)
    subtasks: list[SubTask] = Field(..., min_length=1)
    required_capabilities: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _validate_dag(self) -> "ExecutionPlan":
        task_ids = [task.task_id for task in self.subtasks]
        if len(task_ids) != len(set(task_ids)):
            raise ValueError("ExecutionPlan subtasks must have unique task_id values")

        id_set = set(task_ids)
        adj: dict[str, list[str]] = {task.task_id: list(task.depends_on) for task in self.subtasks}
        for task in self.subtasks:
            for dep in task.depends_on:
                if dep == task.task_id:
                    raise ValueError(f"SubTask '{task.task_id}' cannot depend on itself")
                if dep not in id_set:
                    raise ValueError(
                        f"SubTask '{task.task_id}' references unknown dependency '{dep}'"
                    )

        # Cycle detection via DFS coloring (0=unvisited, 1=visiting, 2=visited)
        state: dict[str, int] = dict.fromkeys(id_set, 0)

        def has_cycle(node: str) -> bool:
            state[node] = 1
            for dep in adj[node]:
                if state[dep] == 1:
                    return True
                if state[dep] == 0 and has_cycle(dep):
                    return True
            state[node] = 2
            return False

        for node in id_set:
            if state[node] == 0 and has_cycle(node):
                raise ValueError("ExecutionPlan contains a cyclic task dependency")

        if not self.required_capabilities:
            caps: list[str] = []
            seen: set[str] = set()
            for task in self.subtasks:
                for cap in task.required_capabilities:
                    if cap not in seen:
                        seen.add(cap)
                        caps.append(cap)
            self.required_capabilities = caps

        return self


class PlannerInput(BaseModel):
    """Input schema for the Planner Agent."""

    request: str = Field(..., min_length=1, max_length=10000)
    constraints: list[str] = Field(default_factory=list)
    available_capabilities: list[str] = Field(default_factory=list)
    context: dict[str, Any] = Field(default_factory=dict)


class PlannerOutput(BaseModel):
    """Output schema for the Planner Agent."""

    plan: ExecutionPlan
    metrics: AgentExecutionMetrics = Field(default_factory=AgentExecutionMetrics)


class ResearchFinding(BaseModel):
    """Structured information unit extracted during research."""

    topic: str = Field(..., min_length=1)
    summary: str = Field(..., min_length=1)
    key_facts: list[str] = Field(default_factory=list)
    sources: list[SourceReference] = Field(default_factory=list)
    confidence: float = Field(default=0.8, ge=0.0, le=1.0)


class ResearchInput(BaseModel):
    """Input schema for the Research Agent."""

    query: str = Field(..., min_length=1, max_length=4096)
    focus_areas: list[str] = Field(default_factory=list)
    documents: list[SourceReference] = Field(default_factory=list)
    max_results: int = Field(default=5, ge=1, le=50)


class ResearchOutput(BaseModel):
    """Output schema for the Research Agent."""

    query: str = Field(..., min_length=1)
    findings: list[ResearchFinding] = Field(..., min_length=1)
    sources: list[SourceReference] = Field(default_factory=list)
    gaps: list[str] = Field(default_factory=list)
    metrics: AgentExecutionMetrics = Field(default_factory=AgentExecutionMetrics)


class ComparisonItem(BaseModel):
    """Comparative evaluation across subjects or options."""

    dimension: str = Field(..., min_length=1)
    observations: dict[str, str] = Field(default_factory=dict)
    takeaway: str = Field(..., min_length=1)


class ClaimValidation(BaseModel):
    """Validation of a claim against available research evidence."""

    claim: str = Field(..., min_length=1)
    verdict: Literal["supported", "partially_supported", "unsupported", "contradicted"]
    evidence: str = Field(..., min_length=1)


class AnalystInput(BaseModel):
    """Input schema for the Analyst Agent."""

    topic: str = Field(..., min_length=1, max_length=4096)
    research_findings: list[ResearchFinding] = Field(..., min_length=1)
    claims_to_validate: list[str] = Field(default_factory=list)
    evaluation_criteria: list[str] = Field(default_factory=list)


class AnalystOutput(BaseModel):
    """Output schema for the Analyst Agent."""

    topic: str = Field(..., min_length=1)
    patterns: list[str] = Field(default_factory=list)
    insights: list[str] = Field(..., min_length=1)
    comparisons: list[ComparisonItem] = Field(default_factory=list)
    claim_validations: list[ClaimValidation] = Field(default_factory=list)
    confidence_score: float = Field(default=0.8, ge=0.0, le=1.0)
    metrics: AgentExecutionMetrics = Field(default_factory=AgentExecutionMetrics)


class ReportSection(BaseModel):
    """A structured section inside a Writer Agent report."""

    heading: str = Field(..., min_length=1)
    content: str = Field(..., min_length=1)


class WriterInput(BaseModel):
    """Input schema for the Writer Agent."""

    goal: str = Field(..., min_length=1, max_length=4096)
    research: ResearchOutput | None = None
    analysis: AnalystOutput | None = None
    output_format: Literal["markdown", "json", "executive_brief"] = "markdown"
    audience: str = Field(default="technical", max_length=128)

    @model_validator(mode="after")
    def _require_source_material(self) -> "WriterInput":
        if self.research is None and self.analysis is None:
            raise ValueError("WriterInput requires at least research or analysis input")
        return self


class WriterOutput(BaseModel):
    """Output schema for the Writer Agent."""

    title: str = Field(..., min_length=1)
    executive_summary: str = Field(..., min_length=1)
    sections: list[ReportSection] = Field(..., min_length=1)
    formatted_content: str = Field(..., min_length=1)
    citations: list[SourceReference] = Field(default_factory=list)
    output_format: Literal["markdown", "json", "executive_brief"] = "markdown"
    metrics: AgentExecutionMetrics = Field(default_factory=AgentExecutionMetrics)

